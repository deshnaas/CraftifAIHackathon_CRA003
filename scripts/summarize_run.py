"""Render a readable Markdown summary of one Sentinel run directory.

Read-only: it never modifies the run's JSON files. Every number in the output is
taken from run.json, summary.json, incidents.json and events.jsonl, plus the demo
manifest (ground truth for synthetic clips) when one is available.

Usage:
    python scripts/summarize_run.py RUN_DIR [--manifest data/demo/manifest.json] [--out RUN_DIR/SUMMARY.md]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


def load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def segment_for(manifest: dict[str, Any] | None, clip: str, t: float) -> dict[str, Any] | None:
    if not manifest:
        return None
    for c in manifest.get("clips", []):
        if c.get("file") == clip:
            for s in c.get("segments", []):
                if s["start_s"] <= t < s["end_s"]:
                    return s
    return None


def summarize(run_dir: Path, manifest_path: Path | None) -> str:
    run = load(run_dir / "run.json")
    summary = load(run_dir / "summary.json") if (run_dir / "summary.json").is_file() else None
    incidents = load(run_dir / "incidents.json")
    events = [json.loads(x) for x in (run_dir / "events.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]
    manifest = load(manifest_path) if manifest_path and manifest_path.is_file() else None
    clip = Path(str(run["source"]).replace("\\", "/")).name

    out = [f"# Run summary: {run['run_id']}", ""]
    out.append("Generated by `scripts/summarize_run.py` from the raw files in this folder (which it does not modify).")
    if run.get("input_kind") in ("synthetic_demo", "derived_demo"):
        out.append("")
        out.append("> **Synthetic footage.** The input is a demo clip with deterministic digital degradations, not a real camera.")
    out += ["", "## Run", "", "| Field | Value |", "|---|---|"]
    for k in ("run_id", "stream_id", "source", "input_kind", "started_at", "detector", "baseline_source"):
        out.append(f"| {k} | `{run.get(k)}` |")
    out.append(f"| baseline_warnings | {run.get('baseline_warnings') or 'none'} |")
    if summary:
        for k in ("frames", "end_reason", "final_state", "incidents", "mean_latency_ms", "max_latency_ms",
                  "corrupt_frames", "reconnects", "error"):
            out.append(f"| {k} | `{summary.get(k)}` |")

    kinds: dict[str, int] = {}
    for e in events:
        kinds[e["event_type"]] = kinds.get(e["event_type"], 0) + 1
    out += ["", "## Events", "", "| Event type | Count |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in sorted(kinds.items())]

    out += ["", "## Incidents", "",
            "Detection delay = incident opened − start of the applied transform (from the manifest).",
            "Recovery = incident resolved − end of the applied transform (clean footage resumes).",
            "",
            "| # | Incident | Applied transform | Category | Opened (s) | Detection delay (s) | Transitions | Peak severity | Recovering from (s) | Resolved (s) | Recovery after clean footage (s) | Status |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for n, i in enumerate(incidents, 1):
        seg = segment_for(manifest, clip, i["opened_stream_time_s"])
        rec = [t for t in i["transitions"] if t["to"] == "RECOVERING"]
        rec_t = rec[-1]["stream_time_s"] if rec else None
        delay = f"{i['opened_stream_time_s'] - seg['start_s']:.3f}" if seg else "n/a"
        recovery = (f"{i['resolved_stream_time_s'] - seg['end_s']:.3f}"
                    if seg and i["resolved_stream_time_s"] is not None else "n/a")
        trans = " → ".join(t["to"] for t in i["transitions"])
        applied = f"{seg['scenario']} {seg['start_s']:g}–{seg['end_s']:g} s" if seg else "unknown"
        out.append(f"| {n} | `{i['incident_id']}` | {applied} | {', '.join(i['categories_seen'])} | "
                   f"{i['opened_stream_time_s']} | {delay} | {trans} | {i['peak_severity']} | {rec_t} | "
                   f"{i['resolved_stream_time_s']} | {recovery} | {i['status']} |")

    out += ["", "## Measurements and thresholds when each incident opened", ""]
    for i in incidents:
        out += [f"### `{i['incident_id']}` ({', '.join(i['categories_seen'])})", "",
                "| Check | Smoothed value | Raw value | Fires (enter) | Clears (exit) | Severe | Active | Severe now |",
                "|---|---|---|---|---|---|---|---|"]
        for c in i["measurements_at_open"]:
            op = "<" if c["direction"] == "below" else ">"
            out.append(f"| {c['check']} | {c['value']} | {c['raw_value']} | {op} {c['enter_threshold']} | "
                       f"{c['exit_threshold']} | {op} {c['severe_threshold']} | {c['active']} | {c['severe']} |")
        out += ["", f"Worst values during the incident: `{json.dumps(i['worst_values'])}`", "", "Evidence (verbatim):", ""]
        out += [f"- `{e}`" for e in i["evidence"]]
        out += ["", "Recommended actions (verbatim):", ""]
        out += [f"- {a}" for a in i["recommended_actions"]]
        out += ["", f"Opened `{i['opened_at']}` · resolved `{i['resolved_at']}` (UTC wall clock) · snapshot `{i['snapshot_path']}`", ""]
    out += ["## Claim", "", f"Every incident carries `claim: {incidents[0]['claim'] if incidents else 'n/a'}`:", "",
            f"> {incidents[0]['disclaimer'] if incidents else ''}", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("run_dir", type=Path)
    p.add_argument("--manifest", type=Path, default=None)
    p.add_argument("--out", type=Path, default=None)
    a = p.parse_args(argv)
    for name in ("run.json", "incidents.json", "events.jsonl"):
        if not (a.run_dir / name).is_file():
            print(f"error: {a.run_dir / name} not found", file=sys.stderr)
            return 2
    text = summarize(a.run_dir, a.manifest)
    out = a.out or a.run_dir / "SUMMARY.md"
    if out.exists():
        print(f"error: {out} already exists; refusing to overwrite", file=sys.stderr)
        return 2
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
